"""Build with the bundled Java dependencies; no package downloads are required."""
import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "dbms" / "lib"
GENERATED = {"Parser.java", "Lexer.java", "sym.java"}


def generate(destination):
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    commands = [
        ["java", "-cp", str(LIB / "java-cup-11.jar"), "java_cup.Main",
         "-parser", "Parser", "-symbols", "sym", "-destdir", str(destination),
         "dbms/sql.cup"],
        ["java", "-jar", str(LIB / "JFlex.jar"), "-d", str(destination),
         "dbms/sql.flex"],
    ]
    for command in commands:
        subprocess.run(command, cwd=ROOT, check=True)
    sanitize_generated_metadata(destination)


def sanitize_generated_metadata(directory):
    """Keep generator headers portable and free of local paths and timestamps."""
    for name in GENERATED:
        path = Path(directory) / name
        text = path.read_text(encoding="utf-8")
        if name == "Lexer.java":
            text = re.sub(
                r"(?m)^(/\* The following code was generated by JFlex [\d.]+) on [^\n]*( \*/)$",
                r"\1\2", text,
            )
            text = re.sub(r"(?m)^ \* on .* from the specification file$",
                          " * from the specification file", text)
            text = re.sub(r"<tt>file:[^<]*</tt>", "<tt>dbms/sql.flex</tt>", text)
        else:
            text = re.sub(r"(?m)^// (?:Mon|Tue|Wed|Thu|Fri|Sat|Sun) [^\n]*\n", "", text)
            text = re.sub(r"(?m)^  \* @version [^\n]*\n", "", text)
        text = "\n".join(line.rstrip() for line in text.splitlines()) + "\n"
        path.write_text(text, encoding="utf-8")


def build(destination, generated=None, tests=False):
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    sources = sorted((ROOT / "dbms").glob("*.java"))
    if generated is not None:
        sources = [path for path in sources if path.name not in GENERATED]
        sources += sorted(Path(generated).glob("*.java"))
    if tests:
        sources += sorted((ROOT / "tests").glob("*.java"))
    # All project classes use the default package. Remove old compiled classes
    # so deleted or renamed entry points cannot remain executable after a build.
    for compiled in destination.glob("*.class"):
        compiled.unlink()
    subprocess.run(
        ["javac", "-encoding", "UTF-8", "-cp", str(LIB / "*"), "-d",
         str(destination), *map(str, sources)], cwd=ROOT, check=True,
    )
    return str(destination) + os.pathsep + str(LIB / "*")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--regenerate", action="store_true",
                        help="Regenerate Parser.java, Lexer.java, and sym.java from their specifications")
    args = parser.parse_args()
    if args.regenerate:
        with tempfile.TemporaryDirectory(prefix="sql-parser-") as directory:
            generate(directory)
            for name in GENERATED:
                shutil.copyfile(Path(directory) / name, ROOT / "dbms" / name)
    output = ROOT / ".build" / "classes"
    build(output)
    print(f"Build passed: {output}")
