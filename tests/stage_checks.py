def check_stages(classpath, home, run_engine, through=None):
    for name, statements in STAGES.items():
        reference = sqlite3.connect(":memory:", isolation_level=None)
        reference.execute("PRAGMA foreign_keys=ON")
        count = 0
        try:
            for batch in [statements, RESTARTS.get(name, [])]:
                if not batch:
                    continue
                for sql, actual in zip(batch, run_engine(classpath, Path(home) / name, batch)):
                    count += 1
                    try:
                        cursor = reference.execute(sql)
                        expected = [list(row) for row in cursor.fetchall()]
                    except sqlite3.Error as error:
                        if "error" not in actual:
                            raise AssertionError(f"[{name}] SQLite rejected {sql}: {error}; engine: {actual}")
                    else:
                        if "error" in actual or actual["rows"] != expected:
                            raise AssertionError(f"[{name}] {sql}\nSQLite: {expected}\nEngine: {actual}")
                        if cursor.rowcount >= 0 or actual["affected"] > 0:
                            # Older Python/SQLite combinations misreport INSERT RETURNING rowcount.
                            affected = reference.execute("SELECT changes()").fetchone()[0]
                            if affected != actual["affected"]:
                                raise AssertionError(f"[{name}] Wrong affected count for {sql}: expected {affected}, got {actual}")
        finally:
            reference.close()
        print(f"Stage {name} passed: {count} SQLite statements, including a new JVM", flush=True)
        if through == name:
            break


